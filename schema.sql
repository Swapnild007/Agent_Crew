CREATE TABLE IF NOT EXISTS owner (id INTEGER PRIMARY KEY CHECK(id=1), salt TEXT NOT NULL, hash TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS sessions (hash TEXT PRIMARY KEY, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS auth_limit (id INTEGER PRIMARY KEY CHECK(id=1), attempts INTEGER NOT NULL, until INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS settings (id INTEGER PRIMARY KEY CHECK(id=1), paused INTEGER NOT NULL DEFAULT 0);
INSERT OR IGNORE INTO settings(id) VALUES(1);
CREATE TABLE IF NOT EXISTS missions (
  id TEXT PRIMARY KEY, objective TEXT NOT NULL, state TEXT NOT NULL,
  step INTEGER NOT NULL DEFAULT 0, created INTEGER NOT NULL, due INTEGER NOT NULL,
  outcome TEXT, approval TEXT, expires INTEGER
);
CREATE TABLE IF NOT EXISTS events (
  id INTEGER PRIMARY KEY AUTOINCREMENT, mission TEXT REFERENCES missions(id),
  kind TEXT NOT NULL, detail TEXT NOT NULL, created INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS artifacts (
  mission TEXT PRIMARY KEY REFERENCES missions(id), body TEXT NOT NULL, hash TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS notes (
  id TEXT PRIMARY KEY, body TEXT NOT NULL, created INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS skills (
  name TEXT NOT NULL, version INTEGER NOT NULL, description TEXT NOT NULL,
  PRIMARY KEY(name,version)
);
